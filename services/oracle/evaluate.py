"""Score every method against what really happened, and write eval/anomaly.md.

The truth comes from the story (docs/case-001.md) and gen_telemetry.py, never
from the CSV a model reads:
- 21 to 29 Oct, 01:00 to 03:59: Node 7 wakes while Ines teaches it her voice.
- 31 Oct, 01:00 (the manual key at 01:58) and 02:00 (the commit at 02:14).
- The decoy: 31 Oct 03:00 is the scheduled Sunday backup, an hour after she
  left. It looks like trouble and isn't.

    uv run python evaluate.py
"""
import json
import sys
from datetime import datetime
from pathlib import Path

import numpy as np

from app.data import load
from app.methods import METHODS

DECOY = "2049-10-31T03:00"


def truth(ts: str) -> bool:
    t = datetime.fromisoformat(ts)
    ingest = datetime(2049, 10, 21) <= t < datetime(2049, 10, 30) and 1 <= t.hour < 4
    return ingest or ts in ("2049-10-31T01:00", "2049-10-31T02:00")


def main() -> None:
    known, unknown = load()
    y = np.array([truth(ts) for ts in unknown.ts])
    rows, raw = [], {}
    for name, fn in METHODS.items():
        r = fn(known, unknown)
        tp = int((r.flagged & y).sum())
        fp = int((r.flagged & ~y).sum())
        fn_ = int((~r.flagged & y).sum())
        p = tp / (tp + fp) if tp + fp else 0.0
        rec = tp / (tp + fn_)
        f1 = 2 * p * rec / (p + rec) if p + rec else 0.0
        flagged = set(unknown.ts[r.flagged])
        missed = sorted(set(unknown.ts[y]) - flagged)
        false = sorted(flagged - set(unknown.ts[y]))
        rows.append((name, r, tp, fp, fn_, p, rec, f1, DECOY in flagged, missed, false))
        raw[name] = {"detail": r.detail, "ms": r.ms, "scores": dict(zip(unknown.ts, map(float, r.scores)))}

    out = [
        "# Anomaly scan: TabPFN against the baselines",
        "",
        f"The oracle judges the {len(unknown)} unlabelled hours (21 to 31 Oct) using the {len(known)} labelled hours before them.",
        f"{int(y.sum())} of the unlabelled hours are real incidents. One more, {DECOY}, is a scheduled backup that looks like one.",
        "Generated by `services/oracle/evaluate.py`. The truth comes from the story, not from anything a model reads.",
        "",
        "## Results",
        "",
        "| Method | Flagged | Precision | Recall | F1 | Flags the backup decoy | Time |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, r, tp, fp, fn_, p, rec, f1, decoy, *_ in rows:
        out.append(f"| {name} | {tp + fp} | {p:.2f} | {rec:.2f} | {f1:.2f} | {'yes' if decoy else 'no'} | {r.ms} ms |")
    out += [
        "",
        "## Reading this",
        "",
        "- The z-score's perfect row is not a fair win. Its threshold (6) and its 0.05 floor on the spread were set by hand in Phase 2, against this same file. TabPFN and IsolationForest run on defaults.",
        "- TabPFN reads the labelled history in one forward pass, with no training and no tuning. It is near certain about the nine nights Node 7 woke, and it leaves the Sunday backup alone because the history holds seven Sunday backups labelled normal.",
        "- It misses one hour, 31 Oct 01:00, when the only thing that moved was a manual key in door E2. No incident in the history involved a manual key, so there was nothing like it in context. In-context learning is only as good as the context.",
        "- IsolationForest knows what normal looks like but not what an incident looks like, so it flags the backup decoy.",
        "- The game shows all three. The anomaly report leads with TabPFN's probabilities and lists every hour where the methods disagree.",
        "",
    ]
    for name, r, *_, missed, false in rows:
        out += [f"### {name}", "", r.detail, "", f"- Missed: {', '.join(missed) or 'none'}", f"- False alarms: {', '.join(false) or 'none'}", ""]
    Path("../../eval/anomaly.md").write_text("\n".join(out))
    Path("../../eval/results").mkdir(exist_ok=True)
    Path("../../eval/results/anomaly.raw.json").write_text(json.dumps(raw, indent=1))
    print("\n".join(out))


if __name__ == "__main__":
    sys.exit(main())
